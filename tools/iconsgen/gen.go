package main

import (
	"bufio"
	"bytes"
	"encoding/json"
	"encoding/xml"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

type options struct {
	Names                                     []string
	LucideDir, LucideVersion, LucideIntegrity string
	SIDir, SIVersion, SIIntegrity             string
}

var (
	nameRE      = regexp.MustCompile(`^(si:)?[a-z0-9-]+$`)
	integrityRE = regexp.MustCompile(`^sha512-[A-Za-z0-9+/]{86}==$`)
	versionRE   = regexp.MustCompile(`^[0-9A-Za-z][0-9A-Za-z.+-]*$`)
	licenseRE   = regexp.MustCompile(`@license lucide-static v(\S+) - ISC`)
)

// Elements and attributes a glyph may use: drawing primitives only, no
// styling, scripting or references (plus fill="currentColor", see walk), so the output cannot carry anything else.
var (
	allowedTags = map[string]bool{"path": true, "circle": true, "rect": true, "line": true, "polyline": true, "polygon": true, "ellipse": true}
	allowedAttr = map[string]bool{"d": true, "cx": true, "cy": true, "r": true, "rx": true, "ry": true, "x": true, "y": true,
		"x1": true, "x2": true, "y1": true, "y2": true, "width": true, "height": true, "points": true}
)

type attr struct{ Key, Val string }

type element struct {
	Tag   string
	Attrs []attr
}

// readNames returns the names in r, one per line, skipping blank lines and
// lines starting with #.
func readNames(r io.Reader) ([]string, error) {
	var names []string
	sc := bufio.NewScanner(r)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		names = append(names, line)
	}
	return names, sc.Err()
}

// generate builds the icons.js text for o.Names. Every problem is an error;
// nothing is skipped.
func generate(o options) ([]byte, error) {
	for _, f := range []struct{ flag, val string }{{"-lucide-version", o.LucideVersion}, {"-si-version", o.SIVersion}} {
		if !versionRE.MatchString(f.val) {
			return nil, fmt.Errorf("%s %q is not a version", f.flag, f.val)
		}
	}
	for _, f := range []struct{ flag, val string }{{"-lucide-integrity", o.LucideIntegrity}, {"-si-integrity", o.SIIntegrity}} {
		if !integrityRE.MatchString(f.val) {
			return nil, fmt.Errorf("%s %q is not sha512-<86 base64 chars>==", f.flag, f.val)
		}
	}
	if len(o.Names) == 0 {
		return nil, errors.New("no icon names")
	}
	for i, n := range o.Names {
		switch {
		case !nameRE.MatchString(n):
			return nil, fmt.Errorf("icon name %q does not match %s", n, nameRE)
		case i > 0 && n == o.Names[i-1]:
			return nil, fmt.Errorf("duplicate icon name %q", n)
		case i > 0 && n < o.Names[i-1]:
			return nil, fmt.Errorf("icon name %q is not sorted (after %q)", n, o.Names[i-1])
		}
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by tools/iconsgen; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// lucide-static %s (ISC) %s  ·  simple-icons %s (CC0-1.0 data; marks are their owners' trademarks, docs/ICONS.md) %s\n",
		o.LucideVersion, abbrev(o.LucideIntegrity), o.SIVersion, abbrev(o.SIIntegrity))
	b.WriteString("// Regenerate: docs/ICONS.md \"Regenerating\".\n")
	fmt.Fprintf(&b, "const ICON_SET_SOURCES = Object.freeze({ lucide: { version: %s, integrity: %s }, simpleIcons: { version: %s, integrity: %s } });\n",
		jstr(o.LucideVersion), jstr(o.LucideIntegrity), jstr(o.SIVersion), jstr(o.SIIntegrity))
	b.WriteString("const ICON_SET = Object.freeze({\n")
	for _, n := range o.Names {
		kind, bare := "s", strings.TrimPrefix(n, "si:")
		var (
			els []element
			err error
		)
		if bare == n {
			els, err = parseLucide(filepath.Join(o.LucideDir, bare+".svg"), o.LucideVersion)
		} else {
			kind = "f"
			els, err = parseSI(filepath.Join(o.SIDir, bare+".svg"))
		}
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "  %s: [%s, [", jstr(n), jstr(kind))
		for i, e := range els {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "[%s, %s]", jstr(e.Tag), attrObject(e.Attrs))
		}
		b.WriteString("]],\n")
	}
	b.WriteString("});\n")
	b.WriteString(`if (typeof module !== "undefined" && module.exports) module.exports = { ICON_SET, ICON_SET_SOURCES };` + "\n")
	return b.Bytes(), nil
}

// abbrev shortens a sha512 integrity for the header comment: first 4 and last
// 5 characters of the digest, e.g. sha512-A9Ug…KLw==.
func abbrev(integrity string) string {
	return integrity[:len("sha512-")+4] + "…" + integrity[len(integrity)-5:]
}

// jstr renders s as a JS string literal. JSON strings are valid JS ones.
func jstr(s string) string {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	_ = enc.Encode(s) // a string always encodes
	return strings.TrimSuffix(b.String(), "\n")
}

func attrObject(as []attr) string {
	if len(as) == 0 {
		return "{}"
	}
	parts := make([]string, len(as))
	for i, a := range as {
		parts[i] = jstr(a.Key) + ": " + jstr(a.Val)
	}
	return "{ " + strings.Join(parts, ", ") + " }"
}

// parseLucide reads a lucide-static file: a license comment naming version,
// a 24x24 svg root and flat drawing elements.
func parseLucide(path, version string) ([]element, error) {
	els, license, err := walk(path, false)
	if err != nil {
		return nil, err
	}
	if license == "" {
		return nil, fmt.Errorf("%s: no @license lucide-static comment", path)
	}
	if license != version {
		return nil, fmt.Errorf("%s: license comment says lucide-static v%s, -lucide-version is %s", path, license, version)
	}
	if len(els) == 0 {
		return nil, fmt.Errorf("%s: no drawable elements", path)
	}
	return els, nil
}

// parseSI reads a simple-icons file: a 24x24 svg root holding exactly one
// <title> and one <path d>.
func parseSI(path string) ([]element, error) {
	els, _, err := walk(path, true)
	if err != nil {
		return nil, err
	}
	if len(els) != 1 || els[0].Tag != "path" || len(els[0].Attrs) != 1 || els[0].Attrs[0].Key != "d" {
		return nil, fmt.Errorf("%s: want exactly one <title> and one <path d>", path)
	}
	return els, nil
}

// walk token-walks one SVG file and returns its drawing elements (class
// dropped, attribute order kept) and the version in its lucide license
// comment. With si, the only other child allowed is one <title>, which is
// checked and dropped.
func walk(path string, si bool) (els []element, license string, err error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, "", err
	}
	fail := func(format string, a ...any) ([]element, string, error) {
		return nil, "", fmt.Errorf("%s: %s", path, fmt.Sprintf(format, a...))
	}
	dec := xml.NewDecoder(bytes.NewReader(raw))
	var (
		depth             int
		seenRoot, inTitle bool
		titles            int
	)
	for {
		tok, err := dec.Token()
		if err == io.EOF {
			break
		}
		if err != nil {
			return fail("%v", err)
		}
		switch t := tok.(type) {
		case xml.Comment:
			if m := licenseRE.FindStringSubmatch(string(t)); m != nil && license == "" {
				license = m[1]
			}
		case xml.StartElement:
			depth++
			switch {
			case depth == 1:
				if seenRoot || t.Name.Local != "svg" {
					return fail("root element is <%s>, want a single <svg>", t.Name.Local)
				}
				seenRoot = true
				vb := ""
				for _, a := range t.Attr {
					if a.Name.Space == "" && a.Name.Local == "viewBox" {
						vb = a.Value
					}
				}
				if vb != "0 0 24 24" {
					return fail(`viewBox is %q, want "0 0 24 24"`, vb)
				}
			case depth > 2 || inTitle:
				return fail("nested element <%s>: glyphs must be flat", t.Name.Local)
			case si && t.Name.Local == "title":
				titles++
				inTitle = true
			case !allowedTags[t.Name.Local] || (si && t.Name.Local != "path"):
				return fail("element <%s> is not allowed", t.Name.Local)
			default:
				e := element{Tag: t.Name.Local}
				for _, a := range t.Attr {
					if a.Name.Space == "" && a.Name.Local == "class" {
						continue
					}
					// fill is allowed only as currentColor: Lucide's filled dots
					// (key-round, vault) keep their fill, any other paint is refused.
					fillOK := a.Name.Local == "fill" && a.Value == "currentColor"
					if a.Name.Space != "" || !(allowedAttr[a.Name.Local] || fillOK) || (si && a.Name.Local != "d") {
						return fail("attribute %s=%q on <%s> is not allowed; pick another glyph or widen the allowlist in gen.go", a.Name.Local, a.Value, e.Tag)
					}
					e.Attrs = append(e.Attrs, attr{a.Name.Local, a.Value})
				}
				els = append(els, e)
			}
		case xml.EndElement:
			depth--
			inTitle = false
		case xml.CharData:
			if !inTitle && len(bytes.TrimSpace(t)) > 0 {
				return fail("unexpected text %q", bytes.TrimSpace(t))
			}
		}
	}
	if !seenRoot {
		return fail("no <svg> root")
	}
	if si && titles != 1 {
		return fail("want exactly one <title> and one <path d>")
	}
	return els, license, nil
}
