func TestGenerateRefuses(t *testing.T) {
	cases := []struct {
		name string
		mut  func(*options)
		want string // substring the error must carry
	}{
		{"unsorted", func(o *options) { o.Names = []string{"tri", "box"} }, "box"},
		{"duplicate", func(o *options) { o.Names = []string{"box", "box"} }, "duplicate"},
		{"uppercase", func(o *options) { o.Names = []string{"Box"} }, "Box"},
		{"traversal", func(o *options) { o.Names = []string{"../x"} }, "../x"},
		{"missing file", func(o *options) { o.Names = []string{"nope"} }, "nope.svg"},
		{"missing si file", func(o *options) { o.Names = []string{"si:nope"} }, "nope.svg"},
		{"version mismatch", func(o *options) { o.LucideVersion = "1.71.0" }, "1.71.0"},
		{"nested g", func(o *options) { o.Names = []string{"bad-g"} }, "bad-g.svg"},
		{"bad attribute", func(o *options) { o.Names = []string{"bad-attr"} }, "bad-attr.svg"},
		{"short lucide integrity", func(o *options) { o.LucideIntegrity = "sha512-short" }, "-lucide-integrity"},
		{"short si integrity", func(o *options) { o.SIIntegrity = "sha512-short" }, "-si-integrity"},
		{"no names", func(o *options) { o.Names = nil }, "no icon names"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			o := fixtureOpts("box")
			c.mut(&o)
			out, err := generate(o)
			if err == nil {
				t.Fatalf("generate succeeded, want an error; output:\n%s", out)
			}
			if !strings.Contains(err.Error(), c.want) {
				t.Errorf("error %q does not name %q", err, c.want)
			}
		})
	}
}

// writeSVG puts one SVG in a temp dir and returns the dir.
func writeSVG(t *testing.T, name, body string) string {
	t.Helper()
	dir := t.TempDir()
	if err := os.WriteFile(dir+"/"+name+".svg", []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
	return dir
}

func TestGenerateRefusesShapes(t *testing.T) {
	const lhead = "<!-- @license lucide-static v1.70.0 - ISC -->\n<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"%s\">\n"
	lucide := func(viewBox, body string) string {
		return strings.Replace(lhead, "%s", viewBox, 1) + body + "</svg>\n"
	}
	good := `<path d="M1 1" />`
	cases := []struct{ name, kind, svg, want string }{
		{"viewBox", "lucide", lucide("0 0 16 16", good), "viewBox"},
		{"no license comment", "lucide", "<svg viewBox=\"0 0 24 24\">" + good + "</svg>", "license"},
		{"disallowed element", "lucide", lucide("0 0 24 24", `<text x="1">a</text>`), "text"},
		{"defs", "lucide", lucide("0 0 24 24", `<defs><path d="M1 1" /></defs>`), "defs"},
		{"no children", "lucide", lucide("0 0 24 24", ""), "no drawable"},
		{"text node", "lucide", lucide("0 0 24 24", good+"hello"), "text"},
		{"namespaced attribute", "lucide", lucide("0 0 24 24", `<path d="M1 1" xlink:href="#a" xmlns:xlink="http://www.w3.org/1999/xlink" />`), "href"},
		{"si two paths", "si", `<svg viewBox="0 0 24 24"><title>A</title><path d="M1 1"/><path d="M2 2"/></svg>`, "exactly"},
		{"si no title", "si", `<svg viewBox="0 0 24 24"><path d="M1 1"/></svg>`, "exactly"},
		{"si extra attr", "si", `<svg viewBox="0 0 24 24"><title>A</title><path d="M1 1" fill="red"/></svg>`, "fill"},
		{"si viewBox", "si", `<svg viewBox="0 0 32 32"><title>A</title><path d="M1 1"/></svg>`, "viewBox"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			o := fixtureOpts("x")
			if c.kind == "si" {
				o.Names = []string{"si:x"}
				o.SIDir = writeSVG(t, "x", c.svg)
			} else {
				o.LucideDir = writeSVG(t, "x", c.svg)
			}
			out, err := generate(o)
			if err == nil {
				t.Fatalf("generate succeeded, want an error; output:\n%s", out)
			}
			if !strings.Contains(err.Error(), "x.svg") || !strings.Contains(err.Error(), c.want) {
				t.Errorf("error %q should name x.svg and %q", err, c.want)
			}
		})
	}
}

func TestReadNames(t *testing.T) {
	in := "# header\n\n  box  \n\t# indented comment\nsi:claude\n\n  tri\n"
	got, err := readNames(strings.NewReader(in))
	if err != nil {
		t.Fatal(err)
	}
	if want := "box,si:claude,tri"; strings.Join(got, ",") != want {
		t.Errorf("readNames = %v, want %s", got, want)
	}
}

func TestRepoNamesSorted(t *testing.T) {
	f, err := os.Open("names.txt")
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	names, err := readNames(f)
	if err != nil {
		t.Fatal(err)
	}
	if !sort.StringsAreSorted(names) {
		t.Error("names.txt is not sorted")
	}
	for i := 1; i < len(names); i++ {
		if names[i] == names[i-1] {
			t.Errorf("names.txt repeats %q", names[i])
		}
	}
}
